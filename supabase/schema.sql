-- ==============================================================================
-- 1. TABEL PAPAN JUARA BEST PLAYER (LEADERBOARD)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.leaderboard (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  name TEXT NOT NULL,
  time_seconds INTEGER NOT NULL,
  score INTEGER NOT NULL,
  wrong_count INTEGER DEFAULT 0 NOT NULL,
  total_questions INTEGER DEFAULT 10 NOT NULL,
  badge TEXT,
  created_at TIMESTAMPTZ DEFAULT now() NOT NULL
);

-- Migrasi untuk tabel yang sudah ada sebelumnya
ALTER TABLE public.leaderboard ADD COLUMN IF NOT EXISTS wrong_count INTEGER DEFAULT 0 NOT NULL;

CREATE INDEX IF NOT EXISTS idx_leaderboard_ranking 
ON public.leaderboard (score DESC, wrong_count ASC, time_seconds ASC);

ALTER TABLE public.leaderboard ENABLE ROW LEVEL SECURITY;

-- Kebijakan RLS Leaderboard
DROP POLICY IF EXISTS "Semua orang dapat membaca leaderboard" ON public.leaderboard;
CREATE POLICY "Semua orang dapat membaca leaderboard" 
ON public.leaderboard FOR SELECT TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "Semua orang dapat menambahkan skor leaderboard" ON public.leaderboard;
CREATE POLICY "Semua orang dapat menambahkan skor leaderboard" 
ON public.leaderboard FOR INSERT TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "Admin dapat menghapus dan mereset leaderboard" ON public.leaderboard;
CREATE POLICY "Admin dapat menghapus dan mereset leaderboard" 
ON public.leaderboard FOR DELETE TO anon, authenticated USING (true);

