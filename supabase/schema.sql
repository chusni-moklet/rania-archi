-- ==============================================================================
-- 2. TABEL SOAL TAMBAHAN DARI ADMIN/GURU (QUESTIONS)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.questions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question TEXT NOT NULL,
  subtext TEXT NOT NULL DEFAULT 'Soal Tambahan Guru',
  options JSONB NOT NULL,
  explanation TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT now() NOT NULL
);

ALTER TABLE public.questions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Semua orang dapat membaca soal" ON public.questions;
CREATE POLICY "Semua orang dapat membaca soal" 
ON public.questions FOR SELECT TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "Admin dapat menambah soal" ON public.questions;
CREATE POLICY "Admin dapat menambah soal" 
ON public.questions FOR INSERT TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "Admin dapat menghapus soal" ON public.questions;
CREATE POLICY "Admin dapat menghapus soal" 
ON public.questions FOR DELETE TO anon, authenticated USING (true);

-- ==============================================================================
